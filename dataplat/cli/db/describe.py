# View dependencies
# ---------------------------------------------------------------------------


def _render_view_dependencies(
    console: Console, counter: _SectionCounter, desc: ViewDescription
) -> None:
    if not desc.upstream and not desc.downstream:
        return
    _print_section_heading(console, counter, "Dependencies", _CAPTION_DEPENDENCIES)

    def _block(title: str, edges: list[Any]) -> str:
        lines = [f"[dim italic]{title}[/dim italic]"]
        if not edges:
            lines.append(f"  {_DASH}")
        else:
            for e in edges:
                lines.append(
                    f"  [dim]•[/dim] {esc(e.qualified_name)} "
                    f"{_dim('(' + esc(e.kind) + ')')}"
                )
        return "\n".join(lines)

    left = _block("Reads from", desc.upstream)
    right = _block("Read by", desc.downstream)

    width = console.size.width or 80
    if desc.upstream and desc.downstream and width >= 100:
        console.print(_indent(Columns([left, right], padding=(0, 6), expand=False)))
    else:
        console.print(_indent(left))
        if desc.downstream:
            console.print()
            console.print(_indent(right))


