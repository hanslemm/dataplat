def _print_title_card_and_gap(
    console: Console,
    *,
    title: str,
    subtitle: str,
    metadata: list[tuple[str, str]],
) -> None:
    card = _title_card(console, title=title, subtitle=subtitle, metadata=metadata)
    console.print(card)
    # Two blank lines between title card and section 1.
    console.print()
    console.print()


def _render_table_description(
    console: Console, desc: TableDescription, engine: SqlEngine
) -> None:
    partitioned = bool(desc.partitioning.children)
    kind = _kind_label(desc.ref.kind, partitioned=partitioned)
    qualified = esc(f"{desc.header.schema}.{desc.header.name}")
    _print_title_card_and_gap(
        console,
        title=qualified,
        subtitle=kind,
        metadata=_table_title_metadata(desc),
    )

    counter = _SectionCounter()
    _render_columns(console, counter, desc, engine)
    _render_indexes(console, counter, desc)
    _render_constraints(console, counter, desc)
    _render_partitioning(console, counter, desc.partitioning)
    _render_privileges(console, counter, desc.privileges)
    _render_triggers(console, counter, desc, "Triggers")
    _render_rls(console, counter, desc)
    _render_redshift_extras(console, counter, desc, engine)
    _render_not_applicable(console, counter, desc.not_applicable, engine)

    # Matview definition last (can be long).
    if desc.definition:
        _print_section_heading(console, counter, "Definition", _CAPTION_DEFINITION)
        syntax = Syntax(
            desc.definition,
            "sql",
            theme="monokai",
            word_wrap=True,
            line_numbers=True,
            padding=(0, 2),
        )
        console.print(_indent(syntax))


def _render_view_description(
    console: Console, desc: ViewDescription, engine: SqlEngine
) -> None:
    qualified = esc(f"{desc.header.schema}.{desc.header.name}")
    kind = "Materialized View" if desc.ref.kind == ObjectKind.matview else "View"
    _print_title_card_and_gap(
        console,
        title=qualified,
        subtitle=kind,
        metadata=_view_title_metadata(desc),
    )

    counter = _SectionCounter()
    _render_columns(console, counter, desc, engine)
    _render_view_dependencies(console, counter, desc)
    _render_privileges(console, counter, desc.privileges)
    _render_triggers(console, counter, desc, "Triggers (INSTEAD OF)")
    _render_not_applicable(console, counter, desc.not_applicable, engine)

    # Definition LAST — it can be hundreds of lines.
    _print_section_heading(console, counter, "Definition", _CAPTION_DEFINITION)
    syntax = Syntax(
        desc.definition.sql,
        "sql",
        theme="monokai",
        word_wrap=True,
        line_numbers=True,
        padding=(0, 2),
    )
    console.print(_indent(syntax))


def _render_schema_privileges(
    console: Console,
    counter: _SectionCounter,
    grants: list[PrivilegeGrant],
) -> None:
    filtered = _filtered_grants(grants)
    if not filtered:
        return
    _print_section_heading(console, counter, "Privileges", _CAPTION_SCHEMA_PRIVILEGES)
    table = _report_table(zebra=len(filtered) > 5)
    table.add_column("Grantee")
    table.add_column("Privilege")
    table.add_column("Grantor", style="dim")
    for g in filtered:
        priv = g.privilege + (" *" if g.with_grant_option else "")
        table.add_row(cell(g.grantee), cell(priv), cell(g.grantor or ""))
    console.print(_indent(table))


def _render_schema_default_privileges(
    console: Console,
    counter: _SectionCounter,
    grants: list[DefaultPrivilegeGrant],
) -> None:
    if not grants:
        return
    _print_section_heading(
        console, counter, "Default privileges", _CAPTION_SCHEMA_DEFAULT_PRIVILEGES
    )
    table = _report_table(zebra=len(grants) > 5)
    table.add_column("Grantee")
    table.add_column("Object type", style="dim")
    table.add_column("Privileges", overflow="fold")
    table.add_column("Granted by", style="dim")
    for g in grants:
        privs = ", ".join(g.privileges)
        if g.with_grant_option:
            privs = f"{privs} *"
        table.add_row(
            cell(g.grantee), cell(g.object_type), cell(privs), cell(g.grantor or "")
        )
    console.print(_indent(table))


def _render_schema_highlights(
    console: Console,
    counter: _SectionCounter,
    desc: SchemaDescription,
) -> None:
    candidates = [
        item
        for item in desc.contents
        if item.size_bytes is not None and item.size_bytes > 0
    ]
    if not candidates:
        return
    top = sorted(candidates, key=lambda it: it.size_bytes or 0, reverse=True)[:5]
    _print_section_heading(console, counter, "Highlights", _CAPTION_SCHEMA_HIGHLIGHTS)
    table = _report_table(zebra=False)
    table.add_column("#", justify="right", style="dim", width=3)
    table.add_column("Name")
    table.add_column("Kind", style="dim")
    table.add_column("Rows", justify="right")
    table.add_column("Size", justify="right")
    for i, item in enumerate(top, start=1):
        table.add_row(
            str(i),
            cell(item.name),
            cell(item.kind),
            _fmt_rows(item.row_estimate),
            _fmt_size(item.size_bytes),
        )
    console.print(_indent(table))


def _render_schema_description(
    console: Console, desc: SchemaDescription, engine: SqlEngine
) -> None:
    _print_title_card_and_gap(
        console,
        title=esc(desc.header.name),
        subtitle="Schema",
        metadata=_schema_title_metadata(desc),
    )

    counter = _SectionCounter()
    _render_schema_privileges(console, counter, desc.privileges)
    _render_schema_default_privileges(console, counter, desc.default_privileges)
    _render_schema_highlights(console, counter, desc)
    if desc.contents:
        _print_section_heading(console, counter, "Contents", _CAPTION_SCHEMA_CONTENTS)
        # An Owner column of blanks would invite the reader to wonder what went
        # wrong. On an engine with no users nothing went wrong, and the
        # Privileges note in _render_not_applicable is where that is explained.
        has_owner = any(item.owner for item in desc.contents)
        table = _report_table(zebra=len(desc.contents) > 5)
        table.add_column("Name")
        table.add_column("Kind", style="dim")
        if has_owner:
            table.add_column("Owner")
        table.add_column("Rows", justify="right")
        table.add_column("Size", justify="right")
        for item in desc.contents:
            row: list[str | Text] = [cell(item.name), cell(item.kind)]
            if has_owner:
                row.append(cell(item.owner))
            row += [_fmt_rows(item.row_estimate), _fmt_size(item.size_bytes)]
            table.add_row(*row)
        console.print(_indent(table))
    _render_not_applicable(console, counter, desc.not_applicable, engine)


def render_description(
    console: Console,
    desc: Description,
    engine: SqlEngine,
) -> None:
    if isinstance(desc, TableDescription):
        _render_table_description(console, desc, engine)
    elif isinstance(desc, ViewDescription):
        _render_view_description(console, desc, engine)
    elif isinstance(desc, SchemaDescription):
        _render_schema_description(console, desc, engine)
    else:
        raise TypeError(f"unsupported description: {type(desc).__name__}")


app = typer.Typer(
    name="describe",
    help="Show metadata for a schema, table, view, or materialized view.",
    invoke_without_command=True,
    no_args_is_help=True,
)


def _split_targets(target: str) -> list[str]:
    """Split a comma-separated target list, ignoring empty/whitespace entries."""
    return [t.strip() for t in target.split(",") if t.strip()]


@app.callback(invoke_without_command=True)
def describe(
    target: str = typer.Argument(
        ...,
        help='"<schema>" or "<schema>.<object>". Comma-separate to describe several '
        '(e.g. "public,public.users,raw.orders").',
    ),
    db_target: str | None = TargetOption,
    engine: SqlEngine | None = EngineOption,
    user: str | None = UserOption,
    password: str | None = PasswordOption,
    database: str | None = DatabaseOption,
    host: str | None = HostOption,
    port: int | None = PortOption,
    sslmode: str | None = SslmodeOption,
    env_prefix: str | None = EnvPrefixOption,
    as_json: bool = JsonOption,
) -> None:
    """Entry point for ``dp db describe <target>``.

    One of the three commands that works on every engine, so it resolves through
    :func:`resolve_any_params_or_exit` and receives whichever param shape the
    target's engine needs. Nothing below has to know which: ``db_session``
    dispatches the driver, ``params.engine`` picks the dialect, and the report
    itself names the sections the engine has no concept of.
    """
    console = Console()
    targets = _split_targets(target)
    if not targets:
        console.print(
            '[red]Error: target must be "<schema>" or "<schema>.<object>"[/red]'
        )
        raise typer.Exit(code=1)

    conn_params = resolve_any_params_or_exit(
        ConnCliParams(
            target=db_target,
            engine=engine,
            user=user,
            password=password,
            database=database,
            host=host,
            port=port,
            sslmode=sslmode,
            env_prefix=env_prefix,
        )
    )

    resolved_engine = conn_params.engine
    failures = 0
    rendered = 0
    json_payload: list[dict] = []
    with db_session(conn_params) as conn, conn.cursor() as cursor:
        for single in targets:
            try:
                ref = resolve_target(cursor, resolved_engine, single)
            except (ValueError, TargetNotFoundError) as exc:
                console.print(f"[red]Error ({esc(single)}): {esc(exc)}[/red]")
                failures += 1
                continue
            if ref.kind == ObjectKind.schema:
                desc: Description = describe_schema(cursor, ref, resolved_engine)
            elif ref.kind == ObjectKind.view:
                desc = describe_view(cursor, ref, resolved_engine)
            else:
                desc = describe_table(cursor, ref, resolved_engine)
            if as_json:
                json_payload.append({"target": single, **dataclasses.asdict(desc)})
            else:
                if rendered > 0:
                    console.print()
                    console.print()
                render_description(console, desc, resolved_engine)
            rendered += 1

    if as_json:
        typer.echo(json.dumps(json_payload, indent=2, default=str))
    if failures and failures == len(targets):
        raise typer.Exit(code=1)
