def _shorten_identity(default: str | None) -> str | None:
    if default == "GENERATED ALWAYS AS IDENTITY":
        return "identity (always)"
    if default == "GENERATED BY DEFAULT AS IDENTITY":
        return "identity (default)"
    return default


def _strip_partition_bounds(bounds: str | None) -> str:
    """``FOR VALUES IN ('x')`` → ``'x'``; ranges and DEFAULT pass through."""
    if not bounds:
        return ""
    b = bounds.strip()
    if b == "DEFAULT" or b.startswith("FOR VALUES FROM"):
        return b
    prefix = "FOR VALUES IN ("
    if b.startswith(prefix) and b.endswith(")"):
        return b[len(prefix) : -1].strip()
    return b


def _summarize_partition_key(key: str | None, strategy: str | None) -> tuple[str, str]:
    """Return ``(strategy_label, columns_label)`` for the summary line."""
    if not key:
        return (strategy or "", "")
    for prefix in ("LIST", "RANGE", "HASH"):
        lower_prefix = f"{prefix} ("
        if key.upper().startswith(lower_prefix):
            inner = key[len(lower_prefix) :].rstrip(")").strip()
            return (prefix, inner)
    return (strategy or "", key)


def _kind_label(kind: ObjectKind, *, partitioned: bool = False) -> str:
    if kind == ObjectKind.matview:
        return "Materialized View"
    if kind == ObjectKind.view:
        return "View"
    if kind == ObjectKind.schema:
        return "Schema"
    if partitioned:
        return "Partitioned Table"
    return "Table"


def _filtered_grants(grants: list[PrivilegeGrant]) -> list[PrivilegeGrant]:
    """Drop OWNER rows (owner is shown in the header)."""
    return [g for g in grants if g.privilege != "OWNER"]


