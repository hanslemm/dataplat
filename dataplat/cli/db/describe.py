def _render_indexes(
    console: Console, counter: _SectionCounter, desc: TableDescription
) -> None:
    if not desc.indexes:
        return
    _print_section_heading(console, counter, "Indexes", _CAPTION_INDEXES)

    has_predicate = any(idx.predicate for idx in desc.indexes)
    table = _report_table(zebra=len(desc.indexes) > 5)
    table.add_column("Name", overflow="fold")
    table.add_column("Kind")
    table.add_column("Columns", overflow="fold")
    table.add_column("Method", style="dim")
    table.add_column("Size", justify="right")
    if has_predicate:
        table.add_column("Predicate", overflow="fold")

    def _key(idx: Any) -> tuple[int, int, str]:
        return (0 if idx.primary else 1, 0 if idx.unique else 1, idx.name)

    for idx in sorted(desc.indexes, key=_key):
        if idx.primary:
            kind = "[cyan]PK[/cyan]"
        elif idx.unique:
            kind = "[bold]UNIQUE[/bold]"
        else:
            kind = _dim("INDEX")
        row: list[str | Text] = [
            cell(idx.name),
            kind,
            cell(", ".join(idx.columns)),
            cell(idx.method),
            _fmt_size(idx.size_bytes),
        ]
        if has_predicate:
            row.append(cell(idx.predicate or ""))
        table.add_row(*row)
    console.print(_indent(table))


