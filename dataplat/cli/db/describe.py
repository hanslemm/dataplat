def _table_title_metadata(desc: TableDescription) -> list[tuple[str, str]]:
    hdr = desc.header
    pairs: list[tuple[str, str]] = []
    if hdr.owner:
        pairs.append(("Owner", esc(hdr.owner)))
    if hdr.tablespace:
        pairs.append(("Tablespace", esc(hdr.tablespace)))
    if hdr.total_size is not None:
        parts: list[str] = []
        if hdr.table_size is not None:
            parts.append(f"table {_fmt_size_plain(hdr.table_size)}")
        if hdr.index_size is not None:
            parts.append(f"index {_fmt_size_plain(hdr.index_size)}")
        if hdr.toast_size is not None:
            parts.append(f"toast {_fmt_size_plain(hdr.toast_size)}")
        size = _fmt_size(hdr.total_size)
        if parts:
            size = f"{size}  {_dim('(' + ' · '.join(parts) + ')')}"
        pairs.append(("Size", size))
    if hdr.row_estimate is not None and hdr.row_estimate >= 0:
        pairs.append(("Rows (est)", _fmt_rows(hdr.row_estimate)))
    if desc.partitioning.children:
        pairs.append(("Partitions", str(len(desc.partitioning.children))))
    if hdr.comment:
        pairs.append(("Comment", esc(hdr.comment)))
    return pairs


def _view_title_metadata(desc: ViewDescription) -> list[tuple[str, str]]:
    hdr = desc.header
    pairs: list[tuple[str, str]] = []
    if hdr.owner:
        pairs.append(("Owner", esc(hdr.owner)))
    pairs.append(("Updatable", "yes" if desc.definition.is_updatable else "no"))
    if desc.definition.check_option:
        pairs.append(("Check option", esc(desc.definition.check_option)))
    if hdr.comment:
        pairs.append(("Comment", esc(hdr.comment)))
    return pairs


def _schema_title_metadata(desc: SchemaDescription) -> list[tuple[str, str]]:
    hdr = desc.header
    counts: dict[str, int] = {}
    for item in desc.contents:
        counts[item.kind] = counts.get(item.kind, 0) + 1

    pairs: list[tuple[str, str]] = []
    if hdr.owner:
        pairs.append(("Owner", esc(hdr.owner)))
    if counts:
        parts = []
        for kind in sorted(counts):
            n = counts[kind]
            label = kind if n == 1 else f"{kind}s"
            parts.append(f"{n} {esc(label)}")
        pairs.append(("Contents", " · ".join(parts)))
    total_size = sum(item.size_bytes or 0 for item in desc.contents)
    if total_size > 0:
        pairs.append(("Size", _fmt_size(total_size)))
    total_rows = sum(
        item.row_estimate or 0
        for item in desc.contents
        if item.row_estimate is not None and item.row_estimate >= 0
    )
    if total_rows > 0:
        pairs.append(("Rows (est)", _fmt_rows(total_rows)))
    if hdr.comment:
        pairs.append(("Comment", esc(hdr.comment)))
    return pairs


