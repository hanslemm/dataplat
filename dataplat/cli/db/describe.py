def _render_columns(
    console: Console,
    counter: _SectionCounter,
    desc: TableDescription | ViewDescription,
    engine: SqlEngine,
) -> None:
    _print_section_heading(console, counter, "Columns", _CAPTION_COLUMNS)

    is_table = isinstance(desc, TableDescription)
    width = console.size.width or 80

    has_default = is_table and any(c.default for c in desc.columns)
    has_fk = is_table and any(c.fk_target_table for c in desc.columns)
    has_comment = any(c.comment for c in desc.columns)
    has_encoding = engine == SqlEngine.redshift and any(
        c.encoding for c in desc.columns
    )

    # Responsive drop order: Comment → FK → Default → Encoding.
    budget = width - 44  # rough slack for mandatory columns + gutter
    if has_comment and budget < 20:
        has_comment = False
    elif has_comment:
        budget -= max(20, width // 6) + 2
    if has_fk and budget < 18:
        has_fk = False
    elif has_fk:
        budget -= 22
    if has_default and budget < 14:
        has_default = False
    if has_encoding and budget < 10:
        has_encoding = False

    comment_width = max(20, width // 6)

    table = _report_table(zebra=len(desc.columns) > 5)
    table.add_column("#", justify="right", style="dim", width=3)
    table.add_column("Name")
    table.add_column("Type", style="dim")
    table.add_column("Nullable")
    if is_table:
        if has_default:
            table.add_column("Default", overflow="fold")
        table.add_column("PK")
        if has_fk:
            table.add_column("FK", overflow="fold")
    if has_comment:
        table.add_column("Comment", overflow="fold")
    if has_encoding:
        table.add_column("Encoding")

    for c in desc.columns:
        row: list[str | Text] = [
            str(c.ordinal),
            cell(c.name),
            cell(c.data_type),
            _dim("not null") if not c.nullable else "",
        ]
        if is_table:
            if has_default:
                row.append(cell(_shorten_identity(c.default) or ""))
            row.append("[cyan]●[/cyan]" if c.is_primary_key else "")
            if has_fk:
                if c.fk_target_table:
                    fk = esc(f"{c.fk_target_table}({c.fk_target_column})")
                    row.append(f"{_dim('→')} {_dim(fk)}")
                else:
                    row.append("")
        if has_comment:
            row.append(cell(c.comment or "", max_length=comment_width))
        if has_encoding:
            row.append(cell(c.encoding or ""))
        table.add_row(*row)

    console.print(_indent(table))

    if isinstance(desc, TableDescription):
        pk = desc.constraints.primary_key
        caption_bits: list[str] = []
        if pk is not None:
            caption_bits.append(
                f"Primary key: {esc(pk.name)} ({esc(', '.join(pk.columns))})"
            )
        caption_bits.append(f"{len(desc.columns)} columns")
        if desc.header.row_estimate is not None and desc.header.row_estimate >= 0:
            caption_bits.append(
                f"~{_fmt_rows(desc.header.row_estimate, colored=False)} rows"
            )
        console.print()
        console.print(f"  [dim]{'  ·  '.join(caption_bits)}[/dim]")


