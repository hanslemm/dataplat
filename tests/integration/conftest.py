"""Fixtures backing the integration suite against a live PostgreSQL server.

Why this exists: every other test in the repo drives a hand-written fake
cursor, which proves that a code path *called* ``execute`` but never that the
SQL it built is valid. An invalid column reference, a Redshift-only construct
on the PostgreSQL path, or a broken GRANT passes a fake and fails on a user's
warehouse. These fixtures hand tests a real psycopg cursor so the server is
the judge.

Environment:

``DP_TEST_PG_DSN``
    Connection string. Defaults to the local test container
    (``postgresql://postgres:postgres@127.0.0.1:55432/dataplat_test``).

``DP_TEST_PG_REQUIRED``
    Truthy => an unreachable database is an ERROR, not a skip. CI sets it so
    these tests can never silently become decoration. Unset => skip, so a
    contributor without Docker still gets a green ``uv run pytest``.
"""

from __future__ import annotations

import itertools
import os
import pathlib
import re
from collections.abc import Iterator, Sequence
from typing import TYPE_CHECKING, LiteralString, NoReturn, Protocol

import pytest

if TYPE_CHECKING:
    from psycopg import Connection, Cursor
    from psycopg.rows import TupleRow

